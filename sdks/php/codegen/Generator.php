<?php

declare(strict_types=1);

namespace Esuiss\Relay\Codegen;

use RuntimeException;
use Symfony\Component\Yaml\Yaml;

/**
 * Generates the operations, the error table and the API version of the PHP SDK from the Relay server contract.
 */
final class Generator
{
    public const VERSION = '1';

    private const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

    private const SKIPPED_TAGS = ['access', 'messaging-inbound'];

    private const PUBLIC_TAGS = ['errors', 'discovery'];

    private const TRANSPORT_HEADERS = [
        'relay-version',
        'relay-beta',
        'idempotency-key',
        'dpop',
        'authorization',
        'relay-tenant',
        'relay-environment',
        'relay-csrf-token',
    ];

    private const BODY_TYPES = ['application/json', 'application/merge-patch+json'];

    private const HEADER = '// Code generated by codegen/generate.php from contracts/openapi/server.yaml. DO NOT EDIT.';

    /** @var array<string, array<mixed>> */
    private array $documents = [];

    public function __construct(
        private readonly string $contract,
        private readonly string $errors,
    ) {
    }

    /**
     * @return array<string, string>
     */
    public function files(): array
    {
        $spec = $this->load($this->contract);

        return [
            'Operations.php' => $this->operations($spec),
            'ErrorTable.php' => $this->errorTable(),
            'Meta.php' => $this->meta($spec),
        ];
    }

    /**
     * @return array<mixed>
     */
    private function load(string $path): array
    {
        $real = realpath($path);
        if ($real === false) {
            throw new RuntimeException('missing file ' . $path);
        }
        if (!isset($this->documents[$real])) {
            $parsed = Yaml::parseFile($real);
            if (!is_array($parsed)) {
                throw new RuntimeException('not a mapping: ' . $real);
            }
            $this->documents[$real] = $parsed;
        }

        return $this->documents[$real];
    }

    /**
     * @param array<mixed> $node
     * @return array{0: array<mixed>, 1: string}
     */
    private function resolve(array $node, string $file): array
    {
        $guard = 0;
        while (isset($node['$ref']) && is_string($node['$ref'])) {
            [$path, $pointer] = array_pad(explode('#', $node['$ref'], 2), 2, '');
            if ($path !== '') {
                $file = (string) realpath(dirname($file) . '/' . $path);
            }
            $data = $this->load($file);
            foreach (explode('/', ltrim($pointer, '/')) as $part) {
                if ($part === '') {
                    continue;
                }
                $part = str_replace(['~1', '~0'], ['/', '~'], $part);
                if (!is_array($data) || !array_key_exists($part, $data)) {
                    throw new RuntimeException('unresolved reference ' . $node['$ref']);
                }
                $data = $data[$part];
            }
            if (!is_array($data)) {
                throw new RuntimeException('reference to a scalar ' . $node['$ref']);
            }
            $node = $data;
            if (++$guard > 64) {
                throw new RuntimeException('reference cycle');
            }
        }

        return [$node, $file];
    }

    /**
     * @param array<mixed> $spec
     */
    private function operations(array $spec): string
    {
        $methods = [];
        $file = (string) realpath($this->contract);
        $paths = is_array($spec['paths'] ?? null) ? $spec['paths'] : [];
        foreach ($paths as $path => $item) {
            $path = (string) $path;
            if (str_starts_with($path, '/inbound/') || !is_array($item)) {
                continue;
            }
            [$item, $itemFile] = $this->resolve($item, $file);
            $shared = is_array($item['parameters'] ?? null) ? $item['parameters'] : [];
            foreach (self::METHODS as $verb) {
                $op = $item[$verb] ?? null;
                if (!is_array($op)) {
                    continue;
                }
                $method = $this->operation($path, $verb, $op, $shared, $itemFile);
                if ($method !== null) {
                    $methods[] = $method;
                }
            }
        }

        $out = "<?php\n\n" . self::HEADER . "\n\ndeclare(strict_types=1);\n\n";
        $out .= "namespace Esuiss\\Relay\\Generated;\n\n";
        $out .= "use Esuiss\\Relay\\Call;\nuse Esuiss\\Relay\\Page;\nuse Esuiss\\Relay\\RequestOptions;\n\n";
        $out .= "/**\n * Operations of the Relay server API (API version " . $this->apiVersion($spec) . ").\n */\n";
        $out .= "trait Operations\n{\n";
        $out .= "    /**\n     * @return array<string, mixed>\n     */\n";
        $out .= "    abstract protected function callJson(Call \$call): array;\n\n";
        $out .= "    abstract protected function callText(Call \$call): string;\n\n";
        $out .= "    abstract protected function callNone(Call \$call): void;\n\n";
        $out .= "    /**\n     * @return Page<array<string, mixed>>\n     */\n";
        $out .= "    abstract protected function callPage(Call \$call): Page;\n";
        foreach ($methods as $method) {
            $out .= "\n" . $method;
        }

        return $out . "}\n";
    }

    /**
     * @param array<mixed> $op
     * @param array<mixed> $shared
     */
    private function operation(string $path, string $verb, array $op, array $shared, string $file): ?string
    {
        $id = $op['operationId'] ?? null;
        if (!is_string($id)) {
            throw new RuntimeException('operation without operationId: ' . $verb . ' ' . $path);
        }
        $tags = is_array($op['tags'] ?? null) ? $op['tags'] : [];
        $tag = is_string($tags[0] ?? null) ? $tags[0] : '';
        if (in_array($tag, self::SKIPPED_TAGS, true)) {
            return null;
        }
        $security = is_array($op['security'] ?? null) ? $op['security'] : [];
        $authenticated = $security !== [];
        if (!$authenticated && !in_array($tag, self::PUBLIC_TAGS, true)) {
            return null;
        }
        if ($authenticated && !$this->accessBearer($security)) {
            return null;
        }

        $body = null;
        if (is_array($op['requestBody'] ?? null)) {
            $body = $this->body($op['requestBody'], $file);
            if ($body === null) {
                return null;
            }
        }

        $parameters = [];
        foreach (array_merge($shared, is_array($op['parameters'] ?? null) ? $op['parameters'] : []) as $raw) {
            if (!is_array($raw)) {
                continue;
            }
            [$parameter, $parameterFile] = $this->resolve($raw, $file);
            $name = (string) ($parameter['name'] ?? '');
            $in = (string) ($parameter['in'] ?? '');
            $parameters[$in . ':' . $name] = [$parameter, $parameterFile];
        }

        $idempotent = isset($parameters['header:Idempotency-Key']);
        $taken = ['body' => true, 'options' => true, 'idempotencyKey' => true];
        $pathArgs = [];
        preg_match_all('/\{([^}]+)\}/', $path, $matches);
        foreach ($matches[1] as $name) {
            if (!isset($parameters['path:' . $name])) {
                throw new RuntimeException('undeclared path parameter ' . $name . ' in ' . $id);
            }
            [$parameter, $parameterFile] = $parameters['path:' . $name];
            $pathArgs[] = $this->argument($parameter, $parameterFile, $taken, true);
        }

        $queryArgs = [];
        $headerArgs = [];
        foreach ($parameters as [$parameter, $parameterFile]) {
            $in = $parameter['in'] ?? '';
            $name = (string) ($parameter['name'] ?? '');
            if ($in === 'query') {
                $queryArgs[] = $this->argument($parameter, $parameterFile, $taken, ($parameter['required'] ?? false) === true);
            } elseif ($in === 'header' && !in_array(strtolower($name), self::TRANSPORT_HEADERS, true)) {
                $headerArgs[] = $this->argument($parameter, $parameterFile, $taken, ($parameter['required'] ?? false) === true);
            }
        }

        $response = $this->response($op, $file, isset($parameters['query:starting_after']));

        $required = $pathArgs;
        $optional = [];
        if ($body !== null) {
            $bodyArg = [
                'php' => 'body',
                'name' => 'body',
                'type' => 'array',
                'doc' => $body['list'] ? 'list<mixed>' : 'array<string, mixed>',
                'required' => $body['required'],
            ];
            if ($body['required']) {
                $required[] = $bodyArg;
            } else {
                $optional[] = $bodyArg;
            }
        }
        foreach (array_merge($queryArgs, $headerArgs) as $arg) {
            if ($arg['required']) {
                $required[] = $arg;
            } else {
                $optional[] = $arg;
            }
        }

        $signature = [];
        $docs = [];
        foreach ($required as $arg) {
            $signature[] = $arg['type'] . ' $' . $arg['php'];
            if ($arg['doc'] !== null) {
                $docs[] = '@param ' . $arg['doc'] . ' $' . $arg['php'];
            }
        }
        foreach ($optional as $arg) {
            $signature[] = '?' . $arg['type'] . ' $' . $arg['php'] . ' = null';
            if ($arg['doc'] !== null) {
                $docs[] = '@param ' . $arg['doc'] . '|null $' . $arg['php'];
            }
        }
        if ($idempotent) {
            $signature[] = '?string $idempotencyKey = null';
        }
        $signature[] = '?RequestOptions $options = null';

        [$returnType, $returnDoc, $caller] = match ($response) {
            'page' => ['Page', 'Page<array<string, mixed>>', 'callPage'],
            'json' => ['array', 'array<string, mixed>', 'callJson'],
            'text' => ['string', null, 'callText'],
            default => ['void', null, 'callNone'],
        };
        if ($returnDoc !== null) {
            $docs[] = '@return ' . $returnDoc;
        }

        $summary = $this->summary($op, $id);
        $out = "    /**\n     * " . $summary . "\n";
        if ($docs !== []) {
            $out .= "     *\n";
            foreach ($docs as $doc) {
                $out .= '     * ' . $doc . "\n";
            }
        }
        $out .= "     */\n";
        $out .= '    public function ' . lcfirst($id) . "(\n";
        foreach ($signature as $part) {
            $out .= '        ' . $part . ",\n";
        }
        $out .= '    ): ' . $returnType . " {\n";

        $fields = [
            "method: '" . strtoupper($verb) . "'",
            'path: ' . $this->literal($path),
        ];
        if ($pathArgs !== []) {
            $fields[] = 'pathParams: ' . $this->map($pathArgs);
        }
        if ($queryArgs !== []) {
            $fields[] = 'query: ' . $this->map($queryArgs);
            $explode = [];
            foreach ($queryArgs as $arg) {
                if ($arg['explode']) {
                    $explode[] = $this->literal($arg['name']);
                }
            }
            if ($explode !== []) {
                $fields[] = 'explode: [' . implode(', ', $explode) . ']';
            }
        }
        if ($headerArgs !== []) {
            $fields[] = 'headers: ' . $this->map($headerArgs);
        }
        if ($body !== null) {
            $fields[] = 'body: $body';
            $fields[] = 'contentType: ' . $this->literal($body['contentType']);
            if ($body['list']) {
                $fields[] = 'bodyIsList: true';
            }
        }
        if ($idempotent) {
            $fields[] = 'idempotent: true';
            $fields[] = 'idempotencyKey: $idempotencyKey';
        }
        if (!$authenticated) {
            $fields[] = 'authenticated: false';
        }
        $fields[] = 'options: $options';

        $statement = $returnType === 'void' ? '$this->' : 'return $this->';
        $out .= '        ' . $statement . $caller . "(new Call(\n";
        foreach ($fields as $field) {
            $out .= '            ' . $field . ",\n";
        }
        $out .= "        ));\n";

        return $out . "    }\n";
    }

    /**
     * @param array<mixed> $security
     */
    private function accessBearer(array $security): bool
    {
        foreach ($security as $requirement) {
            if (is_array($requirement) && array_key_exists('access_bearer', $requirement)) {
                return true;
            }
        }

        return false;
    }

    /**
     * @param array<mixed> $requestBody
     * @return array{required: bool, contentType: string, list: bool}|null
     */
    private function body(array $requestBody, string $file): ?array
    {
        [$requestBody, $bodyFile] = $this->resolve($requestBody, $file);
        $content = is_array($requestBody['content'] ?? null) ? $requestBody['content'] : [];
        foreach (self::BODY_TYPES as $type) {
            $media = $content[$type] ?? null;
            if (!is_array($media)) {
                continue;
            }
            $schema = is_array($media['schema'] ?? null) ? $media['schema'] : [];
            [$schema] = $this->resolve($schema, $bodyFile);

            return [
                'required' => ($requestBody['required'] ?? false) === true,
                'contentType' => $type,
                'list' => $this->primaryType($schema) === 'array',
            ];
        }

        return null;
    }

    /**
     * @param array<mixed> $op
     */
    private function response(array $op, string $file, bool $cursor): string
    {
        $responses = is_array($op['responses'] ?? null) ? $op['responses'] : [];
        $codes = [];
        foreach (array_keys($responses) as $code) {
            $code = (string) $code;
            if (preg_match('/^2\d\d$/', $code) === 1) {
                $codes[] = $code;
            }
        }
        sort($codes);
        $first = null;
        foreach ($codes as $code) {
            $entry = $responses[$code] ?? null;
            if (!is_array($entry)) {
                continue;
            }
            [$entry, $entryFile] = $this->resolve($entry, $file);
            $content = is_array($entry['content'] ?? null) ? $entry['content'] : [];
            $json = $content['application/json'] ?? null;
            if (is_array($json)) {
                $schema = is_array($json['schema'] ?? null) ? $json['schema'] : [];
                if ($cursor && $code === '200' && $this->paginated($schema, $entryFile)) {
                    return 'page';
                }

                return 'json';
            }
            $first ??= $content === [] ? 'none' : 'text';
        }

        return $first ?? 'none';
    }

    /**
     * @param array<mixed> $schema
     */
    private function paginated(array $schema, string $file): bool
    {
        $properties = $this->propertyNames($schema, $file, 0);

        return isset($properties['data'], $properties['has_more'], $properties['next_cursor']);
    }

    /**
     * @param array<mixed> $schema
     * @return array<string, true>
     */
    private function propertyNames(array $schema, string $file, int $depth): array
    {
        if ($depth > 16) {
            return [];
        }
        [$schema, $schemaFile] = $this->resolve($schema, $file);
        $names = [];
        foreach (is_array($schema['allOf'] ?? null) ? $schema['allOf'] : [] as $part) {
            if (is_array($part)) {
                $names = array_merge($names, $this->propertyNames($part, $schemaFile, $depth + 1));
            }
        }
        foreach (array_keys(is_array($schema['properties'] ?? null) ? $schema['properties'] : []) as $name) {
            $names[(string) $name] = true;
        }

        return $names;
    }

    /**
     * @param array<mixed> $parameter
     * @param array<string, true> $taken
     * @return array{php: string, name: string, type: string, doc: string|null, required: bool, explode: bool}
     */
    private function argument(array $parameter, string $file, array &$taken, bool $required): array
    {
        $name = (string) ($parameter['name'] ?? '');
        $php = $this->camel($name);
        while (isset($taken[$php])) {
            $php .= 'Param';
        }
        $taken[$php] = true;

        $schema = is_array($parameter['schema'] ?? null) ? $parameter['schema'] : [];
        [$schema, $schemaFile] = $this->resolve($schema, $file);
        $type = match ($this->primaryType($schema)) {
            'integer' => 'int',
            'number' => 'float',
            'boolean' => 'bool',
            'array' => 'array',
            default => 'string',
        };
        $doc = null;
        if ($type === 'array') {
            $items = is_array($schema['items'] ?? null) ? $schema['items'] : [];
            [$items] = $this->resolve($items, $schemaFile);
            $doc = match ($this->primaryType($items)) {
                'integer' => 'list<int>',
                'number' => 'list<float>',
                'boolean' => 'list<bool>',
                default => 'list<string>',
            };
        }
        $style = $parameter['style'] ?? 'form';
        $explode = ($parameter['explode'] ?? ($style === 'form')) === true;

        return [
            'php' => $php,
            'name' => $name,
            'type' => $type,
            'doc' => $doc,
            'required' => $required,
            'explode' => $type === 'array' && $explode,
        ];
    }

    /**
     * @param array<mixed> $schema
     */
    private function primaryType(array $schema): ?string
    {
        $type = $schema['type'] ?? null;
        if (is_string($type)) {
            return $type;
        }
        if (is_array($type)) {
            foreach ($type as $candidate) {
                if (is_string($candidate) && $candidate !== 'null') {
                    return $candidate;
                }
            }
        }

        return null;
    }

    private function camel(string $name): string
    {
        $parts = preg_split('/[^A-Za-z0-9]+/', $name, -1, PREG_SPLIT_NO_EMPTY);
        if ($parts === false || $parts === []) {
            throw new RuntimeException('unusable parameter name ' . $name);
        }
        $out = strtolower(array_shift($parts));
        foreach ($parts as $part) {
            $out .= ucfirst(strtolower($part));
        }

        return $out;
    }

    /**
     * @param array<mixed> $op
     */
    private function summary(array $op, string $id): string
    {
        $summary = is_string($op['summary'] ?? null) ? trim($op['summary']) : $id;
        $summary = str_replace(['*/', "\n"], ['* /', ' '], $summary);
        if (!str_ends_with($summary, '.')) {
            $summary .= '.';
        }

        return $summary;
    }

    /**
     * @param list<array{php: string, name: string, type: string, doc: string|null, required: bool, explode: bool}> $args
     */
    private function map(array $args): string
    {
        $pairs = [];
        foreach ($args as $arg) {
            $pairs[] = $this->literal($arg['name']) . ' => $' . $arg['php'];
        }

        return '[' . implode(', ', $pairs) . ']';
    }

    private function literal(string $value): string
    {
        return "'" . str_replace(['\\', "'"], ['\\\\', "\\'"], $value) . "'";
    }

    /**
     * @param array<mixed> $spec
     */
    private function apiVersion(array $spec): string
    {
        $info = is_array($spec['info'] ?? null) ? $spec['info'] : [];
        $version = $info['version'] ?? null;
        if (!is_string($version) || $version === '') {
            throw new RuntimeException('the contract has no info.version');
        }

        return $version;
    }

    private function errorTable(): string
    {
        $errors = $this->load($this->errors);
        $codes = is_array($errors['codes'] ?? null) ? $errors['codes'] : [];
        $rows = [];
        foreach ($codes as $entry) {
            if (!is_array($entry) || !is_string($entry['code'] ?? null)) {
                continue;
            }
            $rows[] = '        ' . $this->literal($entry['code']) . " => ['family' => "
                . $this->literal((string) ($entry['family'] ?? '')) . ", 'status' => "
                . (int) ($entry['status'] ?? 0) . ", 'retryable' => "
                . (($entry['retryable'] ?? false) === true ? 'true' : 'false') . '],';
        }

        $defaults = [];
        foreach (is_array($errors['retryable_defaults'] ?? null) ? $errors['retryable_defaults'] : [] as $entry) {
            if (!is_array($entry)) {
                continue;
            }
            $code = is_string($entry['code'] ?? null) ? $this->literal($entry['code']) : 'null';
            $defaults[] = "        ['status' => " . (int) ($entry['status'] ?? 0) . ", 'code' => " . $code
                . ", 'retryable' => " . (($entry['retryable'] ?? false) === true ? 'true' : 'false') . '],';
        }

        $out = "<?php\n\n" . self::HEADER . "\n\ndeclare(strict_types=1);\n\n";
        $out .= "namespace Esuiss\\Relay\\Generated;\n\n";
        $out .= "/**\n * Error codes of the Relay API with their family, status and retryable flag.\n */\n";
        $out .= "final class ErrorTable\n{\n";
        $out .= "    /**\n     * @var list<array{status: int, code: string|null, retryable: bool}>\n     */\n";
        $out .= "    public const RETRYABLE_DEFAULTS = [\n" . implode("\n", $defaults) . "\n    ];\n\n";
        $out .= "    /**\n     * @var array<string, array{family: string, status: int, retryable: bool}>\n     */\n";
        $out .= "    public const CODES = [\n" . implode("\n", $rows) . "\n    ];\n";

        return $out . "}\n";
    }

    /**
     * @param array<mixed> $spec
     */
    private function meta(array $spec): string
    {
        $out = "<?php\n\n" . self::HEADER . "\n\ndeclare(strict_types=1);\n\n";
        $out .= "namespace Esuiss\\Relay\\Generated;\n\n";
        $out .= "/**\n * The API version this SDK is pinned to and the generator version that produced it.\n */\n";
        $out .= "final class Meta\n{\n";
        $out .= '    public const API_VERSION = ' . $this->literal($this->apiVersion($spec)) . ";\n\n";
        $out .= '    public const GENERATOR_VERSION = ' . $this->literal(self::VERSION) . ";\n";

        return $out . "}\n";
    }
}
