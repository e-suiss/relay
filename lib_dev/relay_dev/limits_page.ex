defmodule RelayDev.LimitsPage do
  @moduledoc """
  The "limits, retry schedules, guarantees" page of the documentation, rendered as Markdown from the sources the server itself reads: the contract's `x-relay-limits` (`Relay.Limits`), the newest shipped version of the `channel_parameters` data set (`Relay.ChannelParameters`), the webhook retry schedule of the contract and the error catalog (`Relay.Api.ErrorCatalog`). There is no hand-written copy; the documentation site renders this page with `mix relay.docs.limits`.
  """

  @agent_groups ~w(waitpoint mailbox agent_ceiling agent_operations first_contact encrypted_envelope)
  @guarantee "Relay provides at-least-once delivery with durable idempotency, giving effectively-once processing."
  @parameters "priv/datasets/channel_parameters"

  # X-37
  # X-38
  # X-49
  # API-4
  # AG-53
  @doc "Renders the page from the repository at `root`."
  @spec render(Path.t()) :: String.t()
  def render(root) do
    {version, parameters} = channel_parameters(root)

    [
      intro(),
      guarantee(),
      limits(),
      agent_limits(),
      webhook_schedule(),
      channel_schedule(version, parameters),
      errors()
    ]
    |> List.flatten()
    |> Enum.join("\n")
  end

  # X-38
  @doc "The one guarantee sentence of the documentation."
  @spec guarantee_sentence() :: String.t()
  def guarantee_sentence, do: @guarantee

  defp intro do
    [
      "# Limits, retry schedules and guarantees",
      "",
      "This page is generated by `mix relay.docs.limits` from the API contract " <>
        "(`x-relay-limits`), the shipped `channel_parameters` data set and the error catalog: " <>
        "the same sources the server reads. Change the source, not this page.",
      ""
    ]
  end

  defp guarantee do
    ttl = Relay.Limits.fetch!(["idempotency_key_ttl_hours"])
    key_length = Relay.Limits.fetch!(["idempotency_key_length"])

    [
      "## Guarantee",
      "",
      @guarantee,
      "",
      "Every mutating request carries an `Idempotency-Key` of #{key_length["min"]} to " <>
        "#{key_length["max"]} characters, kept for #{ttl} hours. A repeated request with " <>
        "the same key and body gets the stored response with `Idempotency-Replayed: true`. " <>
        "A problem document for an exceeded limit names it in `limit_name`, `limit` " <>
        "and `actual`.",
      ""
    ]
  end

  defp limits do
    {general, groups} =
      Relay.Limits.all()
      |> Map.drop(@agent_groups)
      |> visible()
      |> Enum.split_with(fn {_key, value} -> not is_map(value) end)

    [
      "## Limits",
      "",
      "Durations are ISO 8601 durations.",
      "",
      group("general", Map.new(general), ""),
      Enum.map(groups, fn {key, value} -> group(key, value, key <> ".") end)
    ]
  end

  defp agent_limits do
    groups = Relay.Limits.all() |> Map.take(@agent_groups) |> visible()

    [
      "## Agent resource limits",
      "",
      "Waitpoints, mailboxes, the agent ceiling, first contact and encrypted envelopes.",
      "",
      Enum.map(groups, fn {key, value} -> group(key, value, key <> ".") end)
    ]
  end

  defp group(title, map, prefix) do
    rows = for {key, value} <- flatten(map, prefix), do: "| `#{key}` | #{value(value)} |"
    ["### #{title}", "", "| Limit | Value |", "|---|---|", rows, ""]
  end

  defp flatten(map, prefix) do
    Enum.flat_map(visible(map), fn
      {key, %{} = value} -> flatten(value, prefix <> key <> ".")
      {key, value} -> [{prefix <> key, value}]
    end)
  end

  defp visible(map) do
    map
    |> Enum.reject(fn {key, _value} -> String.starts_with?(key, "x-relay-") end)
    |> Enum.sort_by(fn {key, _value} -> key end)
  end

  defp value(list) when is_list(list), do: Enum.map_join(list, ", ", &value/1)
  defp value(text) when is_binary(text), do: cell(text)
  defp value(other), do: to_string(other)

  defp webhook_schedule do
    schedule = Relay.Limits.fetch!(["webhook", "retry_schedule"])

    [
      "## Retry schedules",
      "",
      "### Webhook deliveries",
      "",
      "The default schedule waits #{Enum.join(schedule["default"], ", ")} before attempts " <>
        "1 to #{length(schedule["default"])}, each wait with up to " <>
        "#{schedule["jitter_percent"]} % jitter. An endpoint may set its own schedule of " <>
        "#{schedule["attempts"]["min"]} to #{schedule["attempts"]["max"]} attempts spanning " <>
        "#{schedule["window"]["min"]} to #{schedule["window"]["max"]}, each wait between " <>
        "#{schedule["wait"]["min"]} and #{schedule["wait"]["max"]}.",
      ""
    ]
  end

  defp channel_schedule(version, parameters) do
    permanent = Enum.map_join(Relay.ChannelParameters.permanent_classes(), ", ", &"`#{&1}`")

    [
      "### Channel deliveries",
      "",
      "From `channel_parameters` version #{version}. The failure classes #{permanent} are " <>
        "never retried. `exponential` waits a full-jitter random time up to " <>
        "min(cap, base × 2^(n−1)) after the n-th failed attempt; `retry_after` waits the " <>
        "provider's `Retry-After`, or the default when it gives none, plus up to 20 %. " <>
        "An empty key field matches every value.",
      "",
      "| Channel | Provider | Failure class | Condition | Message class | Mode | Base | Cap " <>
        "| Default Retry-After | Max attempts |",
      "|---|---|---|---|---|---|---|---|---|---|",
      Enum.map(parameters["backoff"], &backoff_row/1),
      "",
      "Retry budget: within each window, retries may make up at most the given share of " <>
        "attempts once the minimum number of retries is reached.",
      "",
      "| Channel | Window | Max retry share | Min retries |",
      "|---|---|---|---|",
      Enum.map(parameters["retry_budgets"], &budget_row/1),
      ""
    ]
  end

  defp backoff_row(row) do
    cells = [
      key(row["channel"]),
      key(row["provider"]),
      key(row["failure_class"]),
      key(row["condition"]),
      key(row["message_class"]),
      row["mode"],
      ms(row["base_ms"]),
      ms(row["cap_ms"]),
      ms(row["default_retry_after_ms"]),
      to_string(row["max_attempts"])
    ]

    "| " <> Enum.join(cells, " | ") <> " |"
  end

  defp budget_row(row) do
    share = "#{div(row["max_ratio_bp"], 100)} %"
    cells = [key(row["channel"]), ms(row["window_ms"]), share, to_string(row["min_retries"])]
    "| " <> Enum.join(cells, " | ") <> " |"
  end

  defp key(nil), do: ""
  defp key(text), do: "`#{text}`"

  defp ms(nil), do: ""
  defp ms(ms) when rem(ms, 3_600_000) == 0, do: "#{div(ms, 3_600_000)} h"
  defp ms(ms) when rem(ms, 60_000) == 0, do: "#{div(ms, 60_000)} min"
  defp ms(ms) when rem(ms, 1000) == 0, do: "#{div(ms, 1000)} s"
  defp ms(ms), do: "#{ms} ms"

  defp errors do
    entries =
      Enum.map(Relay.Api.ErrorCatalog.codes(), fn code ->
        {:ok, entry} = Relay.Api.ErrorCatalog.fetch(code)
        entry
      end)

    [
      "## Errors",
      "",
      "Every error is an RFC 9457 problem document whose `type` is `/v1/errors/<code>` on " <>
        "the installation's own address. Retry only when `retryable` is true, after " <>
        "`Retry-After` when it is given.",
      "",
      "### Defaults by status",
      "",
      "| Status | Code | Retryable | Retry-After |",
      "|---|---|---|---|",
      Enum.map(Relay.Api.ErrorCatalog.retryable_defaults(), &default_row/1),
      "",
      "### Error codes",
      "",
      "| Code | Status | Retryable | Retry-After | Title |",
      "|---|---|---|---|---|",
      Enum.map(entries, &code_row/1),
      ""
    ]
  end

  defp default_row(row) do
    wait =
      case {row["retry_after_seconds"], row["retry_after"]} do
        {nil, "window"} -> "end of the rate limit window"
        {nil, _none} -> ""
        {seconds, _kind} -> "#{seconds} s"
      end

    cells = [to_string(row["status"]), key(row["code"]), yes(row["retryable"]), wait]
    "| " <> Enum.join(cells, " | ") <> " |"
  end

  defp code_row(entry) do
    cells = [
      key(entry.code),
      to_string(entry.status),
      yes(entry.retryable),
      wait(entry.retry_after),
      cell(entry.title)
    ]

    "| " <> Enum.join(cells, " | ") <> " |"
  end

  defp wait(%{kind: "fixed", seconds: seconds}), do: "#{seconds} s"
  defp wait(%{kind: "range", seconds: low, max_seconds: high}), do: "#{low}–#{high} s"
  defp wait(%{kind: "window"}), do: "end of the rate limit window"
  defp wait(_none), do: ""

  defp yes(true), do: "yes"
  defp yes(_false), do: "no"

  defp cell(text), do: text |> String.replace("|", "\\|") |> String.replace("\n", " ")

  defp channel_parameters(root) do
    dir = Path.join(root, @parameters)

    {number, path} =
      dir
      |> File.ls!()
      |> Enum.flat_map(fn name ->
        case Regex.run(~r/\Av(\d+)\.json\z/, name) do
          [_, digits] -> [{String.to_integer(digits), Path.join(dir, name)}]
          nil -> []
        end
      end)
      |> Enum.max()

    {"v#{number}", path |> File.read!() |> Jason.decode!()}
  end
end
